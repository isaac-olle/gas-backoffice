#THIS IS THE EQUIVALENT TO THE TERRAFORM CONFIGURATION

#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 \
  --username "${POSTGRES_USER}" \
  --dbname postgres <<EOF

CREATE USER ${ADMIN_USER}
WITH PASSWORD '${ADMIN_PASSWORD}' SUPERUSER;

CREATE DATABASE ${DATABASE_NAME}
    OWNER ${ADMIN_USER};

CREATE USER ${SERVICE_USER}
WITH PASSWORD '${SERVICE_PASSWORD}';

GRANT CONNECT ON DATABASE ${DATABASE_NAME}
TO ${SERVICE_USER};

EOF
